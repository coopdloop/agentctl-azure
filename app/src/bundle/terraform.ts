// Generates the Terraform module call that the GitOps pipeline plans/applies for one agent.
// The module lives in infra/modules/foundry-agent (source is configurable per environment).

import { config } from "../config";
import type { AgentManifest } from "../schema/manifest";

const q = (s: string) => JSON.stringify(s).replace(/\$\{/g, "$${");
/** Pre-rendered HCL expression (not quoted/escaped). */
class Raw {
  constructor(public hcl: string) {}
}
const RAW = (hcl: string) => new Raw(hcl);
const ident = (s: string) => s.replace(/[^a-zA-Z0-9_]/g, "_");

/**
 * Renders attributes the way `terraform fmt` aligns them: "=" signs are aligned across runs of
 * consecutive single-line attributes; a multi-line attribute stands alone and breaks the run.
 */
function renderAttrs(entries: [string, unknown][], indent: number): string {
  const pad = " ".repeat(indent);
  const lines: string[] = [];
  let group: [string, string][] = [];
  const flush = () => {
    const w = Math.max(...group.map(([k]) => k.length));
    for (const [k, v] of group) lines.push(`${pad}${k.padEnd(w)} = ${v}`);
    group = [];
  };
  for (const [k, v] of entries) {
    const rendered = hclValue(v, indent);
    if (rendered.includes("\n")) {
      if (group.length) flush();
      lines.push(`${pad}${k} = ${rendered}`);
    } else group.push([k, rendered]);
  }
  if (group.length) flush();
  return lines.join("\n");
}

function hclKey(k: string) {
  return /^[a-zA-Z_][a-zA-Z0-9_]*$/.test(k) ? k : q(k);
}

function hclValue(v: unknown, indent: number): string {
  const pad = " ".repeat(indent);
  if (v === null || v === undefined) return "null";
  if (v instanceof Raw) return v.hcl;
  if (typeof v === "string") return q(v);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) {
    if (!v.length) return "[]";
    return `[\n${v.map((x) => `${pad}  ${hclValue(x, indent + 2)}`).join(",\n")}\n${pad}]`;
  }
  const entries = Object.entries(v as Record<string, unknown>).map(([k, x]) => [hclKey(k), x] as [string, unknown]);
  if (!entries.length) return "{}";
  return `{\n${renderAttrs(entries, indent + 2)}\n${pad}}`;
}

export function terraformMainTf(m: AgentManifest): string {
  const g = m.spec.guardrails.raiPolicy;
  const rai = {
    name: g.name,
    base_policy_name: g.basePolicy,
    mode: g.mode,
    filters: Object.fromEntries(
      Object.entries(g.filters).map(([k, f]) => [k, { enabled: f.enabled, blocking: f.blocking, severity_threshold: f.severityThreshold }]),
    ),
    jailbreak: g.promptShields.jailbreak,
    indirect_attack: g.promptShields.indirectAttack,
    protected_material_text: g.protectedMaterial.text,
    protected_material_code: g.protectedMaterial.code,
  };
  const args: [string, unknown][] = [
    ["name", m.metadata.name],
    ["environment", m.metadata.environment],
    ["subscription_id", m.spec.foundry.subscriptionId],
    ["resource_group_name", m.spec.foundry.resourceGroup],
    ["foundry_account_name", m.spec.foundry.account],
    ["foundry_project_name", m.spec.foundry.project],
    ["model_deployment_name", m.spec.model.deployment],
    ["identity_type", m.spec.identity.type],
    ["azure_role_assignments", m.spec.identity.azureRoleAssignments.map((r) => ({ scope: r.scope, role: r.role }))],
    ["rai_policy", rai],
    ["attach_rai_policy_to_deployment", false],
  ];
  args.push(["agent_definition_path", RAW('"${path.module}/../foundry/agent-definition.json"')]);
  args.push(["manifest_path", RAW('"${path.module}/../manifest/agent.yaml"')]);
  // Supplied by the GitOps pipeline (platform/terraform/<env>.tfvars), not by the bundle author.
  args.push(["apply_agent_definition", RAW("var.apply_agent_definition")]);
  args.push(["placeholder_values", RAW("var.placeholder_values")]);
  const tags: Record<string, unknown> = {
    "agentctl-agent": m.metadata.name,
    "agentctl-team": m.metadata.team,
    "agentctl-classification": m.metadata.dataClassification,
    ...(m.metadata.costCenter ? { "cost-center": m.metadata.costCenter } : {}),
  };

  return `# Generated by agentctl for agent "${m.metadata.name}". Do not edit by hand —
# change the manifest in agentctl (or manifest/agent.yaml) and regenerate.

variable "apply_agent_definition" {
  description = "Set by the pipeline: create the agent version on the Foundry data plane."
  type        = bool
  default     = false
}

variable "placeholder_values" {
  description = "Set by the pipeline: values for $\${...} placeholders in the agent definition."
  type        = map(string)
  default     = {}
}

module ${q(ident(m.metadata.name))} {
  source = ${q(config.gitops.agentModuleSource)}

${renderAttrs(args, 2)}

  tags = ${hclValue(tags, 2)}
}

output "agent_principal_id" {
  value = module.${ident(m.metadata.name)}.principal_id
}

output "rai_policy_id" {
  value = module.${ident(m.metadata.name)}.rai_policy_id
}
`;
}
