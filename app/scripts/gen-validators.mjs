// Precompiles the JSON Schemas into standalone validator code so the browser never needs
// eval/new Function (keeps the production CSP strict). Runs before dev/build/test.
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "schema");
const load = (f) => JSON.parse(readFileSync(join(dir, f), "utf8"));

const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true } });
addFormats(ajv);
ajv.addSchema(load("agent.schema.json"), "agent");
ajv.addSchema(load("change-request.schema.json"), "changeRequest");

const code = standaloneCode(ajv, { validateAgent: "agent", validateChangeRequest: "changeRequest" });
// Ajv emits CommonJS with require() of its runtime helpers; bundle into one self-contained ESM file.
const tmp = mkdtempSync(join(tmpdir(), "agentctl-ajv-"));
const entry = join(dirname(fileURLToPath(import.meta.url)), "..", "node_modules", ".ajv-standalone.cjs");
writeFileSync(entry, code);
const wrapper = entry.replace(/\.cjs$/, ".mjs");
writeFileSync(
  wrapper,
  `import m from "./.ajv-standalone.cjs";\nexport const validateAgent = m.validateAgent;\nexport const validateChangeRequest = m.validateChangeRequest;\n`,
);
await build({
  entryPoints: [wrapper],
  bundle: true,
  format: "esm",
  platform: "browser",
  minify: true,
  outfile: join(tmp, "out.js"),
  banner: { js: "// @ts-nocheck\n// GENERATED by scripts/gen-validators.mjs - do not edit." },
  footer: { js: "" },
});
let out = readFileSync(join(tmp, "out.js"), "utf8");
writeFileSync(join(dir, "validators.generated.js"), out);
rmSync(tmp, { recursive: true, force: true });
writeFileSync(
  join(dir, "validators.generated.d.ts"),
  `import type { ErrorObject } from "ajv";\ntype V = ((data: unknown) => boolean) & { errors?: ErrorObject[] | null };\nexport const validateAgent: V;\nexport const validateChangeRequest: V;\n`,
);
console.log("validators generated");
