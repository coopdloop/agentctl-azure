// Bundles cli/agentctl-verify.ts into one dependency-free Node file for the agents-gitops repo.
// Output: ../artifacts/agentctl-verify.mjs plus a .sha256 file the pipeline pins.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(appDir, "package.json"), "utf8"));
const outDir = join(appDir, "..", "artifacts");
const out = join(outDir, "agentctl-verify.mjs");
mkdirSync(outDir, { recursive: true });

await build({
  entryPoints: [join(appDir, "cli", "agentctl-verify.ts")],
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  outfile: out,
  legalComments: "eof",
  banner: { js: `#!/usr/bin/env node\n// agentctl-verify ${pkg.version} — GENERATED by app/scripts/build-cli.mjs, do not edit.\nimport { createRequire as __agentctlCreateRequire } from "node:module";\nconst require = __agentctlCreateRequire(import.meta.url);` },
});

const sum = createHash("sha256").update(readFileSync(out)).digest("hex");
writeFileSync(`${out}.sha256`, `${sum}  agentctl-verify.mjs\n`);
console.log(`wrote artifacts/agentctl-verify.mjs (${sum.slice(0, 12)}…)`);
